#!/usr/bin/env bash
# Packs Google's Chrome for Testing headless shell into a small, runtime-unpacked
# bundle for server-side rendering (PDFs, screenshots) in Docker images.
#
#   ./build.sh <out-dir>                 # latest Stable from Google
#   CHROME_VERSION=156.0.8078.80 ./build.sh <out-dir>   # pin a version
#   ZSTD_LEVEL=19 ./build.sh <out-dir>   # smaller (~85MB) but ~2.5 min to pack
#   CHROME_ZIP=shell.zip CHROME_VERSION=156.0.8078.80 ./build.sh <out-dir>
#                                        # use an already-downloaded zip (for
#                                        # builds with no internet; see README)
#
# Default zstd level 9: ~96MB, packs in ~6s, unpacks in under a second.
#
# Needs: bash, curl, unzip, gcc, nm (binutils), tar, node >= 23.8 (zstd).
# Downloads straight from Google's Chrome for Testing bucket; nothing here
# re-hosts Chromium.
set -euo pipefail

OUT="${1:?usage: build.sh <out-dir>}"
HERE="$(cd "$(dirname "$0")" && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

if [ -n "${CHROME_ZIP:-}" ]; then
  : "${CHROME_VERSION:?CHROME_VERSION is required with CHROME_ZIP}"
fi
INDEX="https://googlechromelabs.github.io/chrome-for-testing/last-known-good-versions-with-downloads.json"
if [ -z "${CHROME_VERSION:-}" ]; then
  CHROME_VERSION="$(curl -fsSL "$INDEX" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>console.log(JSON.parse(s).channels.Stable.version))')"
fi
URL="https://storage.googleapis.com/chrome-for-testing-public/${CHROME_VERSION}/linux64/chrome-headless-shell-linux64.zip"
echo "headless-chromium: Chrome ${CHROME_VERSION}"

if [ -n "${CHROME_ZIP:-}" ]; then
  cp "$CHROME_ZIP" "$WORK/shell.zip"
else
  curl -fsSL --retry 3 -o "$WORK/shell.zip" "$URL"
fi
unzip -q "$WORK/shell.zip" -d "$WORK"
SRC="$WORK/chrome-headless-shell-linux64"
BIN="$SRC/chrome-headless-shell"

# libgbm is linked (BIND_NOW, so every symbol must resolve) but only used for
# hardware GPU buffers, which headless rendering never touches. Debian's real
# libgbm drags in Mesa + LLVM (~190MB); a stub exporting the same symbols,
# each reporting "no device", keeps the image small and Chromium falls back to
# software rendering.
mkdir -p "$SRC/lib"
{
  echo '/* Generated by headless-chromium/build.sh: see the comment there. */'
  echo '#include <stddef.h>'
  nm -D --undefined-only "$BIN" | grep -o 'gbm_[a-z_0-9]*' | sort -u | while read -r f; do
    echo "void *$f(void) { return NULL; }"
  done
} > "$WORK/gbm_stub.c"
gcc -shared -fPIC -O2 -Wl,-soname,libgbm.so.1 -o "$SRC/lib/libgbm.so.1" "$WORK/gbm_stub.c"

# Fail loudly if Google adds a shared library the README's apt list lacks.
node "$HERE/check-needed.js" "$BIN"

mkdir -p "$OUT"
tar -cf "$WORK/chromium.tar" -C "$SRC" .
node -e '
  const fs = require("fs"), zlib = require("zlib"), crypto = require("crypto");
  const [tarPath, out, version] = process.argv.slice(1);
  const packed = zlib.zstdCompressSync(fs.readFileSync(tarPath), {
    params: { [zlib.constants.ZSTD_c_compressionLevel]: Number(process.env.ZSTD_LEVEL || 9) },
  });
  fs.writeFileSync(out + "/chromium.tar.zst", packed);
  fs.writeFileSync(out + "/manifest.json", JSON.stringify({
    chromeVersion: version,
    sha256: crypto.createHash("sha256").update(packed).digest("hex"),
    bytes: packed.length,
  }, null, 2) + "\n");
' "$WORK/chromium.tar" "$OUT" "$CHROME_VERSION"
cp "$HERE/index.js" "$OUT/index.js"
cp "$HERE/LICENSE" "$OUT/LICENSE"
echo "headless-chromium: wrote $OUT ($(du -h "$OUT/chromium.tar.zst" | cut -f1))"
